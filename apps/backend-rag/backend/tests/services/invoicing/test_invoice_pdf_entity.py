@pytest.fixture
def generator() -> InvoiceGenerator:
    if not _REPORTLAB_AVAILABLE:
        pytest.fail("reportlab is required for the entity PDF test")
    return InvoiceGenerator()


def render(generator: InvoiceGenerator, entity: InvoiceEntity | None = None) -> str:
    pdf_bytes = generator.generate(
        practice_id=42,
        client_name="Synthetic Client",
        client_email="client@example.test",
        client_phone=None,
        client_address=None,
        practice_type="KITAS",
        practice_description="Synthetic service description",
        quoted_price=1_000_000,
        notes="Synthetic payment note.",
        entity=entity,
    )
    assert pdf_bytes.startswith(b"%PDF")
    reader = PdfReader(io.BytesIO(pdf_bytes))
    return "\n".join(page.extract_text() for page in reader.pages)


def bank_lines(entity: InvoiceEntity) -> list[str]:
    return [
        f"Account Name:\n{entity.bank_account_name}",
        f"Account Number:\n{entity.bank_account_number}",
        f"Bank Name:\n{entity.bank_name}",
        f"Bank Branch:\n{entity.bank_branch}",
        f"Swift Code:\n{entity.bank_swift}",
    ]


def test_pdf_supplies_letterhead_tax_address_bank_and_footer_for_each_entity(generator):
    registry = synthetic_entities()
    others = {key: [e for k, e in registry.items() if k != key] for key in registry}
    for key, entity in registry.items():
        text = render(generator, entity)
        assert entity.company_name in text, key
        assert f"NPWP: {entity.tax_id}" in text, key
        for line in bank_lines(entity):
            assert line in text, f"{key}: {line!r}"
        assert f"{entity.company_name} | Bali, Indonesia" in text, key
        assert "This invoice was automatically generated by Bali Zero CRM" in text, key
        if entity.address is not None:
            assert entity.address in text, key
        for other in others[key]:
            assert other.bank_account_number not in text, key
            assert other.bank_swift not in text, key
            assert other.company_name not in text, key


def test_addressless_entity_introduces_no_extra_line(generator):
    a = synthetic_entities()["cimb_bayu_bali_nol"]
    text = render(generator, a)
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    company_idx = lines.index(a.company_name)
    assert lines[company_idx + 1].startswith("asya@"), (
        "default entity (address None) must not print an address or spacer line"
    )
    assert "Bali, Indonesia" in text
    assert a.bank_account_number in text


def test_addressed_entity_prints_address_line(generator):
    b = synthetic_entities()["mandiri_bali_nol_impresariat"]
    text = render(generator, b)
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    company_idx = lines.index(b.company_name)
    assert lines[company_idx + 1] == b.address
    assert lines[company_idx + 2].startswith("asya@")


def test_omitting_entity_selects_default_entity(generator):
    default = ENTITIES[DEFAULT_ENTITY_KEY]
    text = render(generator)
    assert default.company_name in text
    assert f"NPWP: {default.tax_id}" in text
    assert f"Account Number:\n{default.bank_account_number}" in text
    for entity in synthetic_entities().values():
        assert entity.bank_account_number not in text
