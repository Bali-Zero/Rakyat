"""Law importer: law/<F>/*.json cards + family_<f>.json -> visa_types rows and a deterministic SQL migration."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).parent
PRICES_PATH = HERE.parent.parent.parent / "data" / "bali_zero_official_prices_2026.json"
MIGRATIONS_DIR = HERE.parents[2] / "db" / "migrations_v2"
ROLLBACK_MARKER = "-- === ROLLBACK ==="

#: Applied migrations are immutable: their checksums are pinned by the production ledger.
#: When cards change after a family shipped, the new projection goes into a NEW bundle
#: migration that re-upserts whole families. Each family's history is listed oldest first;
#: its LAST entry is the migration the importer output must match byte-for-byte.
FAMILY_MIGRATIONS: dict[str, tuple[str, ...]] = {
    "C": ("331_visa_types_law_family_c.sql",),
    "E30": ("333_visa_types_law_family_e30.sql",),
    "E28": ("335_visa_types_law_family_e28.sql",),
    "E23": ("338_visa_types_law_family_e23.sql",),
    "E33": ("336_visa_types_law_family_e33.sql", "344_visa_types_law_rulings_2026_10_19.sql"),
    "E31": ("337_visa_types_law_family_e31.sql", "344_visa_types_law_rulings_2026_10_19.sql"),
    "A": ("339_visa_types_law_family_a.sql", "344_visa_types_law_rulings_2026_10_19.sql"),
    "B": ("340_visa_types_law_family_b.sql", "344_visa_types_law_rulings_2026_10_19.sql"),
    "D": ("341_visa_types_law_family_d.sql", "344_visa_types_law_rulings_2026_10_19.sql"),
    "BRIDGING": (
        "342_visa_types_law_family_bridging.sql",
        "344_visa_types_law_rulings_2026_10_19.sql",
    ),
}

#: Bundle migration -> (families in emission order, one-line reason).
BUNDLES: dict[str, tuple[tuple[str, ...], str]] = {
    "344_visa_types_law_rulings_2026_10_19.sql": (
        ("BRIDGING", "E33", "E31", "D", "A", "B"),
        "owner rulings of 2026-10-19 (BRIDGING not extendable; E33E/E33F senior age 55;\n"
        "-- E31C/D/F/G Dependent price keys; D12 180 days per entry; A1/B1 nationality lists)",
    ),
}

LAW_COLUMNS = (
    "family",
    "official_name_id",
    "permit_class",
    "is_sold",
    "price_keys",
    "entry_type",
    "sponsor",
    "apply_channel",
    "initial_stay_days",
    "extendable",
    "max_total_days",
    "max_total_months",
    "itap",
    "law_card",
    "source_url",
    "page_sha256",
    "retrieved_at",
    "card_sha256",
    "verification_status",
    "valid_from",
    "valid_until",
    "superseded_by",
)
CASTS = {
    "stay_options": "jsonb",
    "price_keys": "jsonb",
    "itap": "jsonb",
    "law_card": "jsonb",
    "retrieved_at": "timestamptz",
    "valid_from": "date",
    "valid_until": "date",
}
JSON_COLUMNS = {"price_keys", "itap", "law_card", "stay_options"}

SHA_COLUMNS = ("page_sha256", "card_sha256")

HEADER = """-- GENERATED by backend/services/visa_engine/families/importer.py from law/{family} cards
-- and family_{lower}.json. DO NOT EDIT BY HAND: change the cards, then regenerate with
--   python -m backend.services.visa_engine.families.importer --family {family} --emit-sql > <this file>
-- Only the Law columns are written on conflict; legacy columns (name, category, description,
-- duration, cost_visa, requirements, metadata) are never overwritten.

SET lock_timeout = '5s';
SET statement_timeout = '60s';
"""


def load_prices() -> dict:
    return json.loads(PRICES_PATH.read_text())["services"]


def _check_price_keys(code: str, keys: list[dict], prices: dict) -> None:
    for pk in keys:
        cat, item = pk["category"], pk["item_key"]
        if cat not in prices or item not in prices[cat]:
            raise ValueError(f"{code}: price key {cat!r}/{item!r} not found in price list")


def build_rows(family: str) -> list[dict]:
    fam = family.upper()
    data = json.loads((HERE / f"family_{fam.lower()}.json").read_text())
    prices = load_prices()
    rows = []
    for code in sorted(data["visas"]):
        guide = data["visas"][code]
        path = HERE / "law" / fam / f"{code}.json"
        raw = path.read_bytes()
        card = json.loads(raw)
        price_keys = guide["price_keys"]
        _check_price_keys(code, price_keys, prices)
        rows.append(
            {
                "code": code,
                "category": data["category"],
                "family": fam,
                "official_name_id": card["official_name_id"],
                "permit_class": None if card.get("status") == "NOT_FOUND" else data["permit_class"],
                "is_sold": guide.get("is_sold", True),
                "price_keys": price_keys,
                "entry_type": guide.get("entry_type", data["entry_type"]),
                "sponsor": guide.get(
                    "sponsor",
                    (
                        None
                        if guide["sponsor_required"] is None
                        else "REQUIRED"
                        if guide["sponsor_required"]
                        else "CONDITIONAL"
                    ),
                ),
                "apply_channel": guide.get("apply_channel"),
                "initial_stay_days": guide.get("stay_days"),
                "extendable": guide["extendable"],
                "max_total_days": guide.get("max_total_days"),
                "max_total_months": guide.get("max_total_months"),
                "itap": None,
                "law_card": card,
                "source_url": card["source_url"],
                "page_sha256": card["page_sha256"],
                "retrieved_at": card["retrieved_at"],
                "card_sha256": hashlib.sha256(raw).hexdigest(),
                "verification_status": (
                    "VERIFIED" if card.get("status") == "VERIFIED_FROM_SOURCE" else "TO_VERIFY"
                ),
                "valid_from": None,
                "valid_until": None,
                "superseded_by": None,
            }
        )
        if "stay_options" in guide:
            rows[-1]["stay_options"] = guide["stay_options"]
    return rows


def _text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def literal(column: str, value: Any) -> str:
    if value is None:
        return "NULL"
    if column in JSON_COLUMNS:
        body = json.dumps(value, ensure_ascii=False, sort_keys=True)
        tag = "j"
        while f"${tag}$" in body:
            tag += "j"
        return f"${tag}${body}${tag}$::jsonb"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    text = _text(value)
    return f"{text}::{CASTS[column]}" if column in CASTS else text


def emit_sql(family: str) -> str:
    fam = family.upper()
    rows = build_rows(fam)
    law_columns = _law_columns(rows)
    parts = [HEADER.format(family=fam, lower=fam.lower())]
    parts.append(_case_guard_sql(rows))
    cols = ("code", "name", "category", *law_columns)
    updates = ",\n    ".join(f"{c} = EXCLUDED.{c}" for c in law_columns)
    for row in rows:
        vals = [_text(row["code"]), _text(row["official_name_id"]), _text(row["category"])]
        vals += [literal(c, row[c]) for c in law_columns]
        lines = []
        for col, val in zip(cols, vals, strict=True):
            sep = "," if col != cols[-1] else ""
            # sha256 hex digests are content hashes, not secrets.
            tag = PRAGMA_TAG if col in SHA_COLUMNS else ""
            lines.append(f"{val}{sep}{tag}")
        parts.append(
            f"\nINSERT INTO visa_types ({', '.join(cols)})\nVALUES (\n    "
            + "\n    ".join(lines)
            + f"\n)\nON CONFLICT (code) DO UPDATE SET\n    {updates};\n"
        )
    parts.append(_rollback_sql(rows))
    return "".join(parts)


def _family_body(fam: str) -> str:
    """Guard + upserts for one family: emit_sql without its header and rollback."""
    sql = emit_sql(fam)
    header = HEADER.format(family=fam, lower=fam.lower())
    return sql[len(header) : sql.index(f"\n{ROLLBACK_MARKER}\n")]


PRAGMA_TAG = "  -- pragma: allowlist secret"


def literals_in_migration(text: str) -> dict[str, dict[str, str]]:
    """code -> column -> SQL literal, parsed from the importer-generated INSERTs of ``text``."""
    rows: dict[str, dict[str, str]] = {}
    forward = text.split(f"\n{ROLLBACK_MARKER}\n", 1)[0]
    for block in forward.split("\nINSERT INTO visa_types (")[1:]:
        cols = block.split(")\nVALUES (\n", 1)[0].split(", ")
        body = block.split(")\nVALUES (\n", 1)[1].split("\n)\nON CONFLICT (code)", 1)[0]
        values = []
        for line in body.split("\n"):
            line = line.removeprefix("    ").removesuffix(PRAGMA_TAG)
            values.append(line.removesuffix(","))
        if len(values) != len(cols):
            raise ValueError("unparseable INSERT: one literal per line expected")
        row = dict(zip(cols, values, strict=True))
        rows[row["code"].strip("'")] = row
    return rows


def _rollback_updates(fam: str, bundle: str) -> str:
    """UPDATEs restoring, for each row the bundle changes, the changed columns' previous literals."""
    history = FAMILY_MIGRATIONS[fam]
    previous = history[history.index(bundle) - 1]
    before = literals_in_migration((MIGRATIONS_DIR / previous).read_text())
    rows = build_rows(fam)
    if sorted(before) != sorted(r["code"] for r in rows):
        raise ValueError(f"{bundle}: {fam} codes differ from {previous}; rollback would be lossy")
    parts = []
    for row in rows:
        old = before[row["code"]]
        changed = [c for c in _law_columns(rows) if old.get(c, "NULL") != literal(c, row[c])]
        if not changed:
            continue
        sets = []
        for i, col in enumerate(changed):
            sep = "," if i < len(changed) - 1 else ""
            tag = PRAGMA_TAG if col in SHA_COLUMNS else ""
            sets.append(f"    {col} = {old.get(col, 'NULL')}{sep}{tag}")
        parts.append(
            f"\n-- {row['code']}: restore {', '.join(changed)} from {previous}\n"
            "UPDATE visa_types SET\n" + "\n".join(sets) + f"\nWHERE code = {_text(row['code'])};\n"
        )
    return "".join(parts)


def latest_migration(family: str) -> str:
    return FAMILY_MIGRATIONS[family.upper()][-1]


def emit_bundle_sql(bundle: str) -> str:
    """A bundle migration: re-upsert whole families from the current cards. Its rollback re-runs
    only the changed columns of changed rows to their literals in each family's previous
    (applied, immutable) migration."""
    families, reason = BUNDLES[bundle]
    for fam in families:
        if latest_migration(fam) != bundle:
            raise ValueError(f"{bundle}: {fam} is regenerated by a later migration")
    parts = [
        f"-- GENERATED by backend/services/visa_engine/families/importer.py: {reason}.\n"
        "-- Re-upserts the Law columns of whole families from the current cards; the families'\n"
        "-- earlier migrations are applied and immutable. DO NOT EDIT BY HAND: regenerate with\n"
        f"--   python -m backend.services.visa_engine.families.importer --bundle {bundle} --emit-sql > <this file>\n"
        "-- Legacy columns are never overwritten on conflict.\n"
        "\nSET lock_timeout = '5s';\nSET statement_timeout = '60s';\n"
    ]
    for fam in families:
        parts.append(f"\n-- ---- family {fam} ----\n")
        parts.append(_family_body(fam))
    parts.append(
        f"\n{ROLLBACK_MARKER}\n\n"
        "-- Restores the exact pre-bundle Law values: only rows and columns this bundle changes,\n"
        "-- each set back to its literal in the family's previous (applied, immutable) migration.\n"
    )
    for fam in families:
        parts.append(_rollback_updates(fam, bundle))
    return "".join(parts)


def expected_sql(filename: str, family: str | None = None) -> str:
    """What the importer says ``filename`` must contain (bundle or single-family migration)."""
    if filename in BUNDLES:
        return emit_bundle_sql(filename)
    if family is None:
        raise ValueError(f"{filename}: a single-family migration needs --family")
    return emit_sql(family)


def _law_columns(rows: list[dict]) -> tuple[str, ...]:
    # C's applied migration remains byte-identical; stay options are opt-in per family.
    return (*LAW_COLUMNS, "stay_options") if any("stay_options" in r for r in rows) else LAW_COLUMNS


def _case_guard_sql(rows: list[dict]) -> str:
    codes = ", ".join(_text(r["code"]) for r in rows)
    return (
        "\n-- Guard: refuse to run if a row already holds one of these codes in another case\n"
        "-- (the UNIQUE on code is case-sensitive, so the upsert below would add a duplicate).\n"
        "DO $guard$\nBEGIN\n"
        f"    IF EXISTS (SELECT 1 FROM visa_types WHERE code <> upper(code) AND upper(code) IN ({codes})) THEN\n"
        "        RAISE EXCEPTION 'visa_types holds a non-uppercase duplicate of a family code; fix the case first';\n"
        "    END IF;\n"
        "END\n$guard$;\n"
    )


def _rollback_sql(rows: list[dict]) -> str:
    resets = []
    for c in _law_columns(rows):
        if c == "price_keys":
            resets.append("price_keys = '[]'::jsonb")
        elif c == "verification_status":
            resets.append("verification_status = 'TO_VERIFY'")
        else:
            resets.append(f"{c} = NULL")
    codes = ", ".join(_text(r["code"]) for r in rows)
    return (
        "\n-- === ROLLBACK ===\n\n"
        "-- Clears only the Law columns of these codes; rows and legacy columns stay.\n"
        "UPDATE visa_types SET\n    " + ",\n    ".join(resets) + f"\nWHERE code IN ({codes});\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    target = ap.add_mutually_exclusive_group()
    target.add_argument("--family")
    target.add_argument("--bundle", choices=sorted(BUNDLES))
    ap.add_argument("--emit-sql", action="store_true")
    ap.add_argument("--check", metavar="FILE")
    ap.add_argument(
        "--check-latest",
        action="store_true",
        help="check every family against its latest migration in migrations_v2",
    )
    args = ap.parse_args(argv)
    if args.check_latest:
        drift = [
            name
            for name in sorted({latest_migration(f) for f in FAMILY_MIGRATIONS})
            if (MIGRATIONS_DIR / name).read_text()
            != expected_sql(name, next(f for f in FAMILY_MIGRATIONS if latest_migration(f) == name))
        ]
        for name in drift:
            sys.stderr.write(f"DRIFT: {name} differs from importer output\n")
        return 1 if drift else 0
    if not (args.family or args.bundle):
        ap.error("one of --family / --bundle is required")
    if args.check:
        name = Path(args.check).name
        if args.family and name in BUNDLES:
            # A family whose latest migration is a bundle is checked against the whole bundle.
            if args.family.upper() not in BUNDLES[name][0]:
                sys.stderr.write(f"DRIFT: {args.family} is not part of {name}\n")
                return 1
            sql = emit_bundle_sql(name)
        else:
            sql = emit_bundle_sql(args.bundle) if args.bundle else emit_sql(args.family)
        if Path(args.check).read_text() != sql:
            sys.stderr.write(f"DRIFT: {args.check} differs from importer output\n")
            return 1
        return 0
    if args.emit_sql:
        sql = emit_bundle_sql(args.bundle) if args.bundle else emit_sql(args.family)
        sys.stdout.write(sql)
        return 0
    ap.error("one of --emit-sql / --check is required")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
